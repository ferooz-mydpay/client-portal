# Auto translate any missing string with token substitution
def auto_translate(text):
    if text in D:
        return D[text]
    t = text
    # Replace known phrases first (sorted by length descending)
    for k in sorted(D.keys(), key=lambda x: -len(x)):
        if k in t:
            t = t.replace(k, D[k])
    # Cleanup numbers, Arabic %
    t = t.replace('٪', '%')
    t = t.replace('هـ', 'AH')
    # Arabic digits to western digits
    for ar_d, en_d in zip('٠١٢٣٤٥٦٧٨٩', '0123456789'):
        t = t.replace(ar_d, en_d)
    return t

